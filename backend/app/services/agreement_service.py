def get_all_templates(
    db: Session,
    document_type: str | None = None,
    jurisdiction: str | None = None,
    category: str | None = None,
) -> list[dict]:
    """Return templates from DB; fall back to built-in defaults + file-based library templates."""
    templates = db.query(Template).filter(Template.is_active == True).all()

    if templates:
        result = []
        for t in templates:
            if document_type and t.document_type.lower() != document_type.lower():
                continue
            if jurisdiction and t.jurisdiction.lower() != jurisdiction.lower():
                continue
            result.append({
                "id": t.id,
                "name": t.name,
                "document_type": t.document_type,
                "jurisdiction": t.jurisdiction,
                "version": t.version,
                "category": getattr(t, "category", None) or t.document_type,
                "schema_": t.schema_ or {},
            })
        return result

    # Merge hardcoded defaults + all file-based library templates
    all_defaults = DEFAULT_TEMPLATES + load_all_file_templates()
    if document_type:
        all_defaults = [t for t in all_defaults if document_type.lower() in t.get("document_type", "").lower()]
    if jurisdiction:
        all_defaults = [t for t in all_defaults if jurisdiction.lower() in t.get("jurisdiction", "").lower()]
    if category:
        all_defaults = [t for t in all_defaults if category.lower() in t.get("category", "").lower()]
    return all_defaults


def get_template_categories(db: Session) -> list[dict]:
    """Group all templates by category with counts and metadata."""
    templates = get_all_templates(db)
    category_map: dict[str, list[dict]] = {}
    for t in templates:
        cat = t.get("category") or t.get("document_type") or "General Agreements"
        if cat not in category_map:
            category_map[cat] = []
        category_map[cat].append({
            "id": t["id"],
            "name": t["name"],
            "document_type": t.get("document_type", "Agreement"),
            "jurisdiction": t.get("jurisdiction", "India - Tamil Nadu"),
        })

    return [
        {
            "category": cat_name,
            "count": len(items),
            "templates": items,
        }
        for cat_name, items in sorted(category_map.items())
    ]


def get_template_by_id(db: Session, template_id: str) -> dict | None:
    template = db.query(Template).filter(Template.id == template_id).first()
    if template:
        return {
            "id": template.id,
            "name": template.name,
            "document_type": template.document_type,
            "jurisdiction": template.jurisdiction,
            "version": template.version,
            "schema_": template.schema_ or {},
        }
    # Check hardcoded defaults first
    for t in DEFAULT_TEMPLATES:
        if t["id"] == template_id:
            return t
    # Then check file-based library templates
    return get_template_by_id_from_files(template_id)


def generate_draft(
    db: Session,
    workspace_id: str,
    owner_user_id: str,
    template_id: str | None,
    jurisdiction: str,
    requirements: str,
    document_type: str,
    answers: dict,
    case_id: str | None,
) -> GeneratedDocument:
    """Generate a contract draft using LLM with statutory RAG grounding."""
    llm = get_llm_client()

    template_info = get_template_by_id(db, template_id) if template_id else None
    template_name = template_info["name"] if template_info else document_type

    # Statutory RAG retrieval from ChromaDB legal corpus
    statutory_context = ""
    try:
        from app.rag.rag_manager import get_rag_manager
        rag = get_rag_manager()
        legal_retriever = rag.get_legal_retriever()
        statutory_queries = [
            f"essential elements valid agreement Section 10 Indian Contract Act",
            f"arbitration agreement Section 7 Arbitration and Conciliation Act",
            f"compensation breach damages Section 73 74 Indian Contract Act",
            f"Section 27 agreement in restraint of trade void",
        ]
        hits = []
        for q in statutory_queries:
            hits.extend(legal_retriever.search(q, top_k=2))

        seen = set()
        for h in hits:
            cite = h.citation or (f"{h.title} (Section {h.section})" if h.section else h.title)
            if cite and cite not in seen:
                seen.add(cite)
                statutory_context += f"\n- {cite}: {h.text[:280]}"
    except Exception as e:
        logger.warning(f"ChromaDB retrieval during drafting error: {e}")

    answers_text = "\n".join(f"- {k}: {v}" for k, v in (answers or {}).items())

    user_prompt = f"""Document Type: {template_name}
Target Jurisdiction: {jurisdiction}
Core Requirements: {requirements}

Questionnaire Inputs:
{answers_text if answers_text else "(none provided)"}

Statutory Legal Guidance to Ground Clauses:
{statutory_context if statutory_context else "Ground in the Indian Contract Act 1872, Arbitration & Conciliation Act 1996, and relevant commercial statutory standards."}

Generate a complete, professionally drafted {template_name} in clean Markdown format with numbered sections, recitals, defined terms, protective clauses, and formal execution blocks.
"""

    try:
        content = llm.generate_text(
            system_prompt=DRAFT_SYSTEM_PROMPT,
            user_prompt=user_prompt,
        )
    except Exception as e:
        logger.error(f"Draft generation failed: {e}")
        content = f"# {template_name}\n\n**Error**: Draft generation failed. Please check your GEMINI_API_KEY configuration.\n\n---\n*DRAFT — AI-generated, requires attorney review.*"

    draft = GeneratedDocument(
        workspace_id=workspace_id,
        owner_user_id=owner_user_id,
        case_id=case_id,
        template_id=template_id,
        template_version="1.0",
        input_data={"requirements": requirements, "answers": answers, "jurisdiction": jurisdiction},
        content=content,
        status="draft",
    )
    db.add(draft)
    db.commit()
    db.refresh(draft)
    return draft
